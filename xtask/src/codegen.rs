//! `cargo xtask codegen [--check]`: writes the generated table files from `shared/data/`
//! (ADR-0006). Output is deterministic and rustfmt-clean, so `--check` is a plain byte compare.

// `serde_json::Value[...]` returns `Null` for a missing key or index; it never panics.
#![allow(clippy::indexing_slicing)]

use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};

use anyhow::{Context, Result, bail};
use serde_json::Value;

pub(crate) const MIN_YEAR: i64 = 1901;
const MAX_YEAR: i64 = 2199;
/// Days since 1970-01-01 of BS 1901-01-01 (AD 1844-04-11), ALGORITHM §4.
pub(crate) const EPOCH_UNIX_DAYS: i64 = -45_920;

/// One generated file: where it goes and what it should contain.
struct Output {
    path: PathBuf,
    text: String,
}

pub(crate) fn run(check: bool) -> Result<()> {
    let root = workspace_root();
    let outputs = vec![calendar(&root)?, patro(&root)?];
    let mut stale = Vec::new();
    for out in &outputs {
        let current = fs::read_to_string(&out.path).unwrap_or_default();
        if current == out.text {
            continue;
        }
        if check {
            stale.push(out.path.display().to_string());
        } else {
            if let Some(dir) = out.path.parent() {
                fs::create_dir_all(dir)?;
            }
            fs::write(&out.path, &out.text)
                .with_context(|| format!("writing {}", out.path.display()))?;
            println!("wrote {}", out.path.display());
        }
    }
    if !stale.is_empty() {
        bail!(
            "generated code is stale: run `cargo xtask codegen` ({})",
            stale.join(", ")
        );
    }
    Ok(())
}

pub(crate) fn workspace_root() -> PathBuf {
    let xtask = Path::new(env!("CARGO_MANIFEST_DIR"));
    xtask.parent().unwrap_or(xtask).to_path_buf()
}

pub(crate) fn read_json(path: &Path) -> Result<Value> {
    let text = fs::read_to_string(path).with_context(|| format!("reading {}", path.display()))?;
    serde_json::from_str(&text).with_context(|| format!("parsing {}", path.display()))
}

/// `crates/nepdate/src/generated/calendar.rs`: `PACKED_YEARS`, two bits per month.
fn calendar(root: &Path) -> Result<Output> {
    let json = read_json(&root.join("shared/data/calendar/bs-calendar.json"))?;
    let commit = json["source"]["commit"]
        .as_str()
        .context("source.commit missing")?;
    if json["min_year"].as_i64() != Some(MIN_YEAR) || json["max_year"].as_i64() != Some(MAX_YEAR) {
        bail!("bs-calendar.json: expected years {MIN_YEAR} to {MAX_YEAR}");
    }
    let epoch_ad = json["epoch"]["ad"].as_str().context("epoch.ad missing")?;
    if epoch_ad != "1844-04-11" || days_from_civil(1844, 4, 11) != EPOCH_UNIX_DAYS {
        bail!("bs-calendar.json: epoch {epoch_ad} doesn't match EPOCH_UNIX_DAYS {EPOCH_UNIX_DAYS}");
    }
    let lengths = json["month_lengths"]
        .as_object()
        .context("month_lengths missing")?;
    let years = usize::try_from(MAX_YEAR - MIN_YEAR + 1)?;
    if lengths.len() != years {
        bail!(
            "bs-calendar.json: {} years in month_lengths, expected {years}",
            lengths.len()
        );
    }

    let mut rows = String::new();
    for year in MIN_YEAR..=MAX_YEAR {
        let months = lengths[&year.to_string()]
            .as_array()
            .with_context(|| format!("year {year} missing"))?;
        if months.len() != 12 {
            bail!("year {year}: {} months, expected 12", months.len());
        }
        let mut packed = 0u32;
        let mut shown = Vec::with_capacity(12);
        for (index, value) in months.iter().enumerate() {
            let length = value.as_u64().unwrap_or(0);
            if !(29..=32).contains(&length) {
                bail!(
                    "year {year} month {}: length {length} not in 29..=32",
                    index + 1
                );
            }
            packed |= u32::try_from(length - 29)? << (index * 2);
            shown.push(length.to_string());
        }
        let hex = format!("{packed:08X}");
        let (high, low) = hex.split_at(4);
        writeln!(rows, "    0x{high}_{low}, // {year}: {}", shown.join(" "))?;
    }

    let text = format!(
        "// @generated by `cargo xtask codegen` from shared/data/calendar/bs-calendar.json. DO NOT EDIT.
// Source: https://github.com/RajuPrasai/NepDate @ {commit} (MIT). See shared/data/NOTICE.

/// First supported BS year.
pub(crate) const MIN_YEAR: u16 = {MIN_YEAR};
/// Last supported BS year.
pub(crate) const MAX_YEAR: u16 = {MAX_YEAR};
/// Number of supported years.
pub(crate) const YEARS: usize = {years};
/// Days since 1970-01-01 of 1901-01-01 BS (= 1844-04-11 AD).
pub(crate) const EPOCH_UNIX_DAYS: i32 = -45_920;

/// Month lengths, 2 bits per month: `length - 29`. Month 1 in bits 0..2.
// `const`, not `static`: const fns (build_month_info, NepaliDate::new) must read it at
// compile time, which is only guaranteed for consts on our MSRV.
pub(crate) const PACKED_YEARS: [u32; YEARS] = [
{rows}];
"
    );
    Ok(Output {
        path: root.join("crates/nepdate/src/generated/calendar.rs"),
        text,
    })
}

/// ALGORITHM §5, the same formula the library uses, to check the epoch while generating.
pub(crate) fn days_from_civil(y: i64, m: i64, d: i64) -> i64 {
    let y = if m <= 2 { y - 1 } else { y };
    let era = if y >= 0 { y } else { y - 399 } / 400;
    let yoe = y - era * 400;
    let mp = (m + 9) % 12;
    let doy = (153 * mp + 2) / 5 + d - 1;
    let doe = yoe * 365 + yoe / 4 - yoe / 100 + doy;
    era * 146_097 + doe - 719_468
}

/// `crates/nepdate-patro/src/generated/patro.rs`: the per-day patro tables.
fn patro(root: &Path) -> Result<Output> {
    let lengths = crate::patro::read_lengths(root)?;
    let data = crate::patro::read(root)?;
    let summary = crate::patro::read_summary(root)?;
    Ok(Output {
        path: root.join("crates/nepdate-patro/src/generated/patro.rs"),
        text: crate::patro::generate(&lengths, &data, &summary)?,
    })
}
